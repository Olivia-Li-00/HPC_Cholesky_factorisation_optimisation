/**
 * @file:
 *      test_correctness.cpp
 * @brief:
 *      Correctness test suite for the Cholesky factorisation implementation
 *
 *      Provides three independent test sets to verify the factorisation:
 *      1. Small known-answer test based on the C2 example from the coursework,
 *         checking both the output matrix and the log-determinant
 *      2. Large-matrix reconstruction test verifying L * L^T = C and the
 *         log-determinant using the reference value calculated from known library
 *      3. Multi-thread consistency test ensuring the log-determinant is
 *         identical across varying OpenMP thread counts
 *
 *      Returns 0 if all tests pass, 1 otherwise.
 */

#include "cholesky_factorisation.h"
#include "utils.h"
#include <cmath>
#include <cstdio>
#include <vector>
#include <omp.h> // Needed for the test in multi-threaded implementations (using omp_set_num_threads to set the number of threads used in the test)
                 // for non-parallel versions this call has no effect
#include <Eigen/Dense>

// Floating point tolerance
#define FLOAT_TOL 1e-8

/**
 * @brief:
 *      Verify Cholesky factorisation against the C2 coursework example
 *
 *      Tests the 2x2 input matrix C2 = {{4, 2}, {2, 26}} and checks:
 *      1. The factorisation completes without error
 *      2. The in-place output matrix matches the expected result
 *         {{2, 1}, {1, 5}} (note: this is the packed L&L^T output,
 *         not L alone)
 *      3. The log-determinant computed via compute_log_det() equals
 *         log(100), the known log|C2|
 *
 * @return:
 *      The number of failed sub-tests (0 if all pass)
 */
int test1(){
    printf("\nTest set 1: Cholesky factorisation of the C2 input matrix example from the coursework should match expected output matrix and expected log determinant\n");

    int failed_tests = 0;

    double c[4] = {4.0, 2.0, 2.0, 26.0};
    long n = 2;
    double t = cholesky_factorisation(c,n);

    // Test if the algorithm completes
    if (t < 0.0) {
        printf("[FAIL] Cholesky factorisation returned an error.\n");
        failed_tests++;
    } 
    else {
        printf("[PASS] Cholesky factorisation succeeded.\n");
    }

    // Test if it gets the expected output matrix from the required function interface
    double expected_output[4] = {2.0, 1.0, 1.0, 5.0};
    int correct_output_pass = 1;
    for (long i=0; i<4; i++) {
        if (fabs(c[i] - expected_output[i]) > FLOAT_TOL) {
            printf("[FAIL] Element [%ld,%ld]: computed %.8f, expected_output %.8f\n", i/n, i%n, c[i], expected_output[i]);
            correct_output_pass = 0;
        }
    }
    if (correct_output_pass == 1) {
        printf("[PASS] All matrix elements computed match expected output matrix.\n");
    }
    else {
        failed_tests++;
    }

    // Test if the equation 4 on log determinant from the coursework is satified, i.e., log|C2|
    double log_determinant = compute_log_det(c, n);
    double expected_log_determinant = log(100); // ground truth log determinant of matrix c (2x2 matrix)
    if (fabs(log_determinant - expected_log_determinant) < FLOAT_TOL) {
        printf("[PASS] Log determinant rule satisfied.\n");
    }
    else {
        printf("[FAIL] Log determinant rule failed.\n");
        failed_tests++;
    }

    return failed_tests;
}

/**
 * @brief:
 *      Verify factorisation correctness of a large matrix via matrix reconstruction and log determinant
 *
 *      For an n x n symmetric positive-definite matrix generated by populate_matrix():
 *      1. Saves a copy of the original matrix
 *      2. Runs cholesky_factorisation() in-place
 *      3. Extracts the lower-triangular factor L and upper-triangular
 *         factor L^T from the output
 *      4. Computes the product L * L^T and compares element-wise
 *         against the original matrix, reporting the maximum error
 *      5. Computes the log determinant using the output matrix and equation 4. and compared
 *         with the reference value obtained by external library
 *
 * @param const long n: Dimension of the square matrix to test
 *
 * @return:
 *      The number of failed sub-tests (0 if all pass)
 */
int test2(const long n){
    printf("\nTest set 2: Large input matrix reconstruction by matrix multiplication (L * L^T = C)\n");

    int failed_tests = 0;

    std::vector<double> c_original(n*n);
    std::vector<double> c(n*n);
    populate_matrix(c.data(), n);
    for (long i=0; i<n*n; i++) {
        c_original[i] = c[i];
    }
    double t = cholesky_factorisation(c.data(), n);

    // Test if the algorithm completes
    if (t < 0.0) {
        printf("[FAIL] Cholesky factorisation returned an error.\n");
        failed_tests++;
    }
    else {
        printf("[PASS] Cholesky factorisation succeeded.\n");
    }

    // Extract L from the lower triangle of c (after cholesky factorisation in-place calculation)
    std::vector<double> L(n*n, 0.0);
    for (long i=0; i<n; i++) {
        for (long j=0; j<=i; j++) {
            L[n*i+j] = c[n*i+j];
        }
    }
    
    // Extract L^T from the upper triangle of c (after cholesky factorisation in-place calculation)
    std::vector<double> LT(n*n, 0.0);
    for (long i=0; i<n; i++) {
        for (long j=i; j<n; j++) {
            LT[n*i+j] = c[n*i+j];
        }
    }

    // Compute L * L^T and compare every element with the original input matrix to find the maximum error
    double max_error = 0.0;
    for (long i=0; i<n; i++) {
        for (long j=0; j<n; j++) {
            double sum = 0.0;
            for (long k=0; k<n; k++) {
                sum += L[n*i+k] * LT[n*k+j];
            }
            double element_error = fabs(sum - c_original[n*i+j]);
            if (element_error > max_error) {
                max_error = element_error;
            }
        }
    }

    printf("Maximum input matrix reconstruction error: %.3e\n", max_error);
    if (max_error < FLOAT_TOL) {
        printf("[PASS] Input matrix successfully reconstructed.\n");
    }
    else {
        printf("[FAIL] Reconstruction error too large (above tolerance %.3e), input matrix was not considered as successfully reconstructed.\n", FLOAT_TOL);
        failed_tests++;
    }

    // Compute log determinant from factorised matrix using equation 4
    double log_det = compute_log_det(c.data(), n);

    // Compute reference log determinant using Eigen library
    Eigen::MatrixXd C_eigen(n, n);
    for (long i = 0; i < n; i++) {
        for (long j = 0; j < n; j++) {
            C_eigen(i, j) = c_original[n * i + j];
        }
    }

    double ref_log_det = log(C_eigen.determinant());

    double log_det_diff = fabs(log_det - ref_log_det);

    if (log_det_diff < FLOAT_TOL) {
        printf("[PASS] Log determinant matches reference.\n");
    }
    else {
        printf("[FAIL] Log determinant mismatch (diff = %.3e, exceeds tolerance %.3e).\n", log_det_diff, FLOAT_TOL);
        failed_tests++;
    }

    return failed_tests;
}

/**
 * @brief:
 *      Verify that the factorisation produces identical results
 *      across different OpenMP thread counts
 *
 *      Runs the factorisation on an n x n symmetric positive-definite matrix with
 *      1, 2, 4, and 8 threads. The single-thread result establishes
 *      a reference log-determinant; subsequent runs must match it
 *      within the floating-point tolerance.
 *
 *      This test is needed in multi-threaded implementations. For single thread implementations the
 *      omp_set_num_threads() calls have no effect.
 *
 * @param const long n: Dimension of the square matrix to test
 *
 * @return:
 *      The number of failed sub-tests (0 if all pass)
 */
int test3(const long n) {
    printf("\nTest set 3: Multi-thread consistency check (log|C| should be identical across thread counts)\n");

    int failed_tests = 0;

    int thread_counts[] = {1, 2, 4, 8};
    int num_configs = 4;
    double reference_log_det = 0.0;

    for (int t_idx = 0; t_idx < num_configs; t_idx++) {
        // Set the number of OpenMP threads for this run;
        // for non-parallel versions this call has no effect
        omp_set_num_threads(thread_counts[t_idx]);

        std::vector<double> c(n*n);
        populate_matrix(c.data(), n);
        double t = cholesky_factorisation(c.data(), n);

        if (t < 0.0) {
            printf("[FAIL] Factorisation failed with %d thread(s).\n", thread_counts[t_idx]);
            failed_tests++;
            continue;
        }

        double log_det = compute_log_det(c.data(), n);

        if (t_idx == 0) {
            // First run (1 thread) establishes the reference value
            reference_log_det = log_det;
            printf("[PASS] Reference log|C| with %d thread:  %.10f\n", thread_counts[t_idx], log_det);
        } else {
            double diff = fabs(log_det - reference_log_det);
            if (diff < FLOAT_TOL) {
                printf("[PASS] %d threads: log|C| = %.10f (diff = %.3e)\n", thread_counts[t_idx], log_det, diff);
            } else {
                printf("[FAIL] %d threads: log|C| = %.10f (diff = %.3e, exceeds tolerance)\n", thread_counts[t_idx], log_det, diff);
                failed_tests++;
            }
        }
    }

    return failed_tests;
}

/**
 * @brief:
 *      Entry point to runs all test sets
 *
 *      Executes:
 *      - test1: C2 known-answer test (2x2)
 *      - test2: Large matrix test (50x50)
 *      - test3: multi-thread consistency test (200x200)
 *
 *      Prints a final pass/fail summary with the total number of
 *      failed tests.
 *
 * @return:
 *      0 if all tests pass, 1 if any test fails
 */
int main() {

    printf("========================================\n");
    printf("Cholesky factorisation correctness tests\n");
    printf("========================================\n");

    int total_failed_tests = test1() + test2(50) + test3(200);

    // Summary
    printf("\n========================================\n");
    if (total_failed_tests == 0) {
        printf("All correctness tests PASSED.\n");
    }
    else {
        printf("%d test(s) FAILED.\n", total_failed_tests);
    }
    printf("========================================\n");

    return (total_failed_tests == 0) ? 0 : 1;
}
